-- --------------------------------------------------------
-- 7. Triggers for updated_at
-- --------------------------------------------------------

create or replace function handle_review_queue_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql security definer;

create trigger handle_review_queue_updated_at_trigger
  after update on review_queue
  for each row
  execute function handle_review_queue_updated_at();

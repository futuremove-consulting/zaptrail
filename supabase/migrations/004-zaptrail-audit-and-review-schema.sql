-- ZT-010 — ZapTrail Semantic Audit Trail & Human Review Inbox Schema
-- Ponytail: minimal schema using Supabase building blocks, English identifiers only, strict RLS by workspace_id/tenant_id

-- --------------------------------------------------------
-- 1. origin_messages — Raw message provenance & deduplication
-- --------------------------------------------------------

create table if not exists origin_messages (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references workspaces(id) on delete cascade,
  tenant_id text not null,
  provider text not null,
  external_message_id text not null,
  conversation_id text not null,
  sender_id text not null,
  direction text not null default 'inbound',
  raw_text text not null,
  normalized_text text not null,
  metadata jsonb not null default '{}'::jsonb,
  sent_at timestamptz not null default now(),
  created_at timestamptz not null default now(),

  unique(workspace_id, provider, external_message_id)
);

comment on table origin_messages is 'Immutable record of inbound/outbound messages processed by ZapTrail pipeline';
comment on column origin_messages.external_message_id is 'Provider message identifier for deduplication';
comment on column origin_messages.tenant_id is 'Organizational tenant scope identifier';

-- --------------------------------------------------------
-- 2. extraction_runs — Persisted interpretation envelopes
-- --------------------------------------------------------

create table if not exists extraction_runs (
  id uuid primary key default gen_random_uuid(),
  envelope_id text not null unique,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  tenant_id text not null,
  conversation_id text not null,
  turn_id text not null,
  domain_key text not null,
  parser_version text not null,
  extractor_type text not null default 'rule',
  llm_invoked boolean not null default false,
  llm_error boolean not null default false,
  review_required boolean not null default false,
  envelope_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

comment on table extraction_runs is 'Audit trail of every interpretation run and resulting envelope';
comment on column extraction_runs.envelope_id is 'Deterministic unique envelope ID generated by the core engine';
comment on column extraction_runs.envelope_payload is 'Full serialized UniversalInterpretationEnvelope';

-- --------------------------------------------------------
-- 3. evidence_spans — Fine-grained quote character offsets
-- --------------------------------------------------------

create table if not exists evidence_spans (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references workspaces(id) on delete cascade,
  tenant_id text not null,
  extraction_run_id uuid references extraction_runs(id) on delete cascade,
  origin_message_id uuid references origin_messages(id) on delete set null,
  external_message_id text not null,
  target_id text not null,
  exact_quote text not null,
  char_start integer,
  char_end integer,
  epistemic_status text not null default 'inferred',
  confidence numeric not null default 0.5,
  hallucination_detected boolean not null default false,
  created_at timestamptz not null default now()
);

comment on table evidence_spans is 'Granular evidence quotes with character offsets for dual-timeline highlighting';
comment on column evidence_spans.exact_quote is 'Verbatim substring from origin message';
comment on column evidence_spans.epistemic_status is 'Epistemic validity: declared, inferred, validated_external, validated_human, superseded, rejected';

-- --------------------------------------------------------
-- 4. review_queue — Human Review Inbox items
-- --------------------------------------------------------

create table if not exists review_queue (
  id uuid primary key default gen_random_uuid(),
  review_id text not null,
  workspace_id uuid not null references workspaces(id) on delete cascade,
  tenant_id text not null,
  conversation_id text not null,
  extraction_run_id uuid references extraction_runs(id) on delete set null,
  origin_message_id uuid references origin_messages(id) on delete set null,
  target_id text not null,
  severity text not null check (severity in ('low', 'medium', 'high')),
  reason text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'edited', 'rejected')),
  original_payload jsonb not null default '{}'::jsonb,
  resolved_payload jsonb,
  evidence_refs jsonb not null default '[]'::jsonb,
  reviewer_id uuid references auth.users(id) on delete set null,
  reviewer_notes text,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  unique(tenant_id, review_id)
);

comment on table review_queue is 'Items flagged for human review due to ambiguity, low confidence, or conflicting values';
comment on column review_queue.status is 'Review status: pending, approved, edited, rejected';
comment on column review_queue.original_payload is 'Preserved original extracted value or observation';
comment on column review_queue.resolved_payload is 'Human operator corrected or confirmed payload';


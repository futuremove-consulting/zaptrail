-- origin_messages policies
create policy "Users can view origin messages in their workspaces"
  on origin_messages
  for select
  using (exists (
    select 1 from memberships
    where workspace_id = origin_messages.workspace_id
    and user_id = auth.uid()
    and status = 'active'
  ));

create policy "Users can insert origin messages in their workspaces"
